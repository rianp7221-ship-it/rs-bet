-- ---------- TABELAS ----------
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text,
  username text,
  balance numeric(14,2) not null default 0 check (balance >= 0),
  is_admin boolean not null default false,
  blocked boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.matches (
  id bigint generated by default as identity primary key,
  external_id text unique,
  sport text not null default 'Futebol',
  league text not null,
  home text not null,
  away text not null,
  starts_at timestamptz not null,
  odd_home numeric(8,2) check (odd_home > 1),
  odd_draw numeric(8,2) check (odd_draw > 1),
  odd_away numeric(8,2) check (odd_away > 1),
  status text not null default 'open' check (status in ('open','live','closed','settled','canceled')),
  result text check (result in ('home','draw','away')),
  score_home int,
  score_away int,
  created_at timestamptz not null default now()
);
create index if not exists matches_status_idx on public.matches (status, starts_at);

create table if not exists public.bets (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  stake numeric(14,2) not null check (stake > 0),
  total_odd numeric(12,2) not null,
  potential numeric(14,2) not null,
  status text not null default 'pending' check (status in ('pending','won','lost','canceled','cashout')),
  cashout_amount numeric(14,2),
  created_at timestamptz not null default now(),
  settled_at timestamptz
);
create index if not exists bets_user_idx on public.bets (user_id, created_at desc);

create table if not exists public.bet_selections (
  id bigint generated by default as identity primary key,
  bet_id bigint not null references public.bets(id) on delete cascade,
  match_id bigint not null references public.matches(id) on delete restrict,
  pick text not null check (pick in ('home','draw','away')),
  odd numeric(8,2) not null,
  status text not null default 'pending' check (status in ('pending','won','lost','canceled'))
);
create index if not exists bet_selections_match_idx on public.bet_selections (match_id);
create index if not exists bet_selections_bet_idx on public.bet_selections (bet_id);

create table if not exists public.transactions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  type text not null,  -- deposit, withdraw, bet, win, cashout, casino_bet, casino_win, adjust, refund
  amount numeric(14,2) not null,
  status text not null default 'done' check (status in ('pending','done','rejected')),
  description text,
  provider_id text,
  created_at timestamptz not null default now()
);
create index if not exists transactions_user_idx on public.transactions (user_id, created_at desc);

create table if not exists public.casino_games (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  game text not null check (game in ('mines','dice')),
  stake numeric(14,2) not null check (stake > 0),
  mines int,
  bombs int[],
  revealed int[] not null default '{}',
  target int,
  over boolean,
  roll numeric(5,2),
  multiplier numeric(12,4) not null default 1,
  payout numeric(14,2) not null default 0,
  status text not null default 'active' check (status in ('active','won','lost')),
  created_at timestamptz not null default now()
);
create index if not exists casino_games_user_idx on public.casino_games (user_id, created_at desc);
create unique index if not exists one_active_mines on public.casino_games (user_id) where game = 'mines' and status = 'active';

