create or replace function public.request_deposit(p_amount numeric) returns bigint
language plpgsql security definer set search_path = public as $$
declare v_user uuid := public._me(); v_id bigint;
begin
  if p_amount is null or p_amount < 10 then raise exception 'Depósito mínimo: R$ 10,00'; end if;
  insert into public.transactions (user_id, type, amount, status, description)
  values (v_user, 'deposit', round(p_amount, 2), 'pending', 'Depósito PIX') returning id into v_id;
  return v_id;
end $$;

create or replace function public.request_withdraw(p_amount numeric) returns bigint
language plpgsql security definer set search_path = public as $$
declare v_user uuid := public._me(); v_id bigint;
begin
  if p_amount is null or p_amount < 20 then raise exception 'Saque mínimo: R$ 20,00'; end if;
  update public.profiles set balance = balance - round(p_amount, 2) where id = v_user and balance >= round(p_amount, 2);
  if not found then raise exception 'Saldo insuficiente'; end if;
  insert into public.transactions (user_id, type, amount, status, description)
  values (v_user, 'withdraw', -round(p_amount, 2), 'pending', 'Saque PIX') returning id into v_id;
  return v_id;
end $$;

create or replace function public.admin_review_transaction(p_tx bigint, p_approve boolean) returns void
language plpgsql security definer set search_path = public as $$
declare v_t public.transactions;
begin
  perform public._require_admin();
  select * into v_t from public.transactions where id = p_tx and status = 'pending' for update;
  if not found then raise exception 'Transação não está pendente'; end if;
  update public.transactions set status = case when p_approve then 'done' else 'rejected' end where id = p_tx;
  if v_t.type = 'deposit' and p_approve then
    update public.profiles set balance = balance + v_t.amount where id = v_t.user_id;
  elsif v_t.type = 'withdraw' and not p_approve then
    perform public._move(v_t.user_id, abs(v_t.amount), 'refund', 'Saque #' || p_tx || ' recusado');
  end if;
end $$;

create or replace function public.admin_adjust_balance(p_user uuid, p_amount numeric, p_reason text) returns void
language plpgsql security definer set search_path = public as $$
begin
  perform public._require_admin();
  perform public._move(p_user, round(p_amount, 2), 'adjust', coalesce(nullif(p_reason, ''), 'Ajuste manual'));
end $$;

create or replace function public.admin_set_blocked(p_user uuid, p_blocked boolean) returns void
language plpgsql security definer set search_path = public as $$
begin
  perform public._require_admin();
  update public.profiles set blocked = p_blocked where id = p_user;
end $$;

-- ---------- CASSINO: MINES ----------
create or replace function public.mines_start(p_stake numeric, p_mines int) returns json
language plpgsql security definer set search_path = public as $$
declare v_user uuid := public._me(); v_id bigint;
begin
  if p_stake is null or p_stake < 1 then raise exception 'Aposta mínima: R$ 1,00'; end if;
  if p_mines is null or p_mines < 1 or p_mines > 24 then raise exception 'Escolha de 1 a 24 minas'; end if;
  if exists (select 1 from public.casino_games where user_id = v_user and game = 'mines' and status = 'active') then
    raise exception 'Você já tem uma partida de Mines em andamento';
  end if;
  perform public._move(v_user, -p_stake, 'casino_bet', 'Mines');
  insert into public.casino_games (user_id, game, stake, mines, bombs)
  values (v_user, 'mines', p_stake, p_mines,
          (select array_agg(c) from (select c from generate_series(0, 24) c order by gen_random_uuid() limit p_mines) x))
  returning id into v_id;
  return json_build_object('id', v_id, 'stake', p_stake, 'mines', p_mines);
end $$;

create or replace function public.mines_reveal(p_game bigint, p_cell int) returns json
language plpgsql security definer set search_path = public as $$
declare v_user uuid := public._me(); g public.casino_games; v_mult numeric; v_pay numeric;
begin
  select * into g from public.casino_games where id = p_game and user_id = v_user and game = 'mines' and status = 'active' for update;
  if not found then raise exception 'Partida não encontrada'; end if;
  if p_cell < 0 or p_cell > 24 or p_cell = any(g.revealed) then raise exception 'Casa inválida'; end if;

  if p_cell = any(g.bombs) then
    update public.casino_games set status = 'lost', payout = 0, multiplier = 0 where id = p_game;
    return json_build_object('bomb', true, 'bombs', g.bombs);
  end if;

  g.revealed := g.revealed || p_cell;
  v_mult := public._mines_mult(g.mines, cardinality(g.revealed));
  if cardinality(g.revealed) = 25 - g.mines then
    v_pay := round(g.stake * v_mult, 2);
    update public.casino_games set revealed = g.revealed, multiplier = v_mult, payout = v_pay, status = 'won' where id = p_game;
    perform public._move(v_user, v_pay, 'casino_win', 'Mines #' || p_game);
    return json_build_object('bomb', false, 'cashout', true, 'bombs', g.bombs, 'payout', v_pay, 'multiplier', v_mult);
  end if;
  update public.casino_games set revealed = g.revealed, multiplier = v_mult where id = p_game;
  return json_build_object('bomb', false, 'multiplier', v_mult);
end $$;

create or replace function public.mines_cashout(p_game bigint) returns json
language plpgsql security definer set search_path = public as $$
declare v_user uuid := public._me(); g public.casino_games; v_pay numeric;
begin
  select * into g from public.casino_games where id = p_game and user_id = v_user and game = 'mines' and status = 'active' for update;
  if not found then raise exception 'Partida não encontrada'; end if;
  v_pay := round(g.stake * g.multiplier, 2);
  update public.casino_games set payout = v_pay, status = 'won' where id = p_game;
  perform public._move(v_user, v_pay, 'casino_win', 'Mines #' || p_game);
  return json_build_object('bombs', g.bombs, 'payout', v_pay);
end $$;

-- ---------- CASSINO: DADOS ----------
create or replace function public.dice_roll(p_stake numeric, p_target int, p_over boolean) returns json
language plpgsql security definer set search_path = public as $$
declare v_user uuid := public._me(); v_chance int; v_roll numeric; v_win boolean; v_mult numeric; v_pay numeric := 0;
begin
  if p_stake is null or p_stake < 1 then raise exception 'Aposta mínima: R$ 1,00'; end if;
  v_chance := case when p_over then 100 - p_target else p_target end;
  if v_chance is null or v_chance < 2 or v_chance > 95 then raise exception 'Chance deve ficar entre 2%% e 95%%'; end if;
  v_mult := round(97.0 / v_chance, 4);
  v_roll := (('x' || substr(md5(gen_random_uuid()::text), 1, 8))::bit(32)::bigint % 10000) / 100.0;
  v_win := case when p_over then v_roll > p_target else v_roll < p_target end;
  perform public._move(v_user, -p_stake, 'casino_bet', 'Dados');
  if v_win then
    v_pay := round(p_stake * v_mult, 2);
    perform public._move(v_user, v_pay, 'casino_win', 'Dados');
  end if;
  insert into public.casino_games (user_id, game, stake, target, over, roll, multiplier, payout, status)
  values (v_user, 'dice', p_stake, p_target, p_over, v_roll, v_mult, v_pay, case when v_win then 'won' else 'lost' end);
  return json_build_object('roll', v_roll, 'win', v_win, 'payout', v_pay);
end $$;

