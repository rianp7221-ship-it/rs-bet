CREATE OR REPLACE FUNCTION public.place_bet(p_selections jsonb, p_stake numeric)
 RETURNS bigint
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  v_user uuid := public._me();
  v_sel jsonb; v_m public.matches; v_odd numeric; v_total numeric := 1; v_bet bigint;
  v_n int := jsonb_array_length(p_selections); v_live boolean := false;
  v_live_max numeric := coalesce((public._setting('live_bet_max_stake'))::text::numeric, 0);
  v_omin numeric := coalesce((public._setting('bet_odd_min'))::text::numeric, 0);
  v_omax numeric := coalesce((public._setting('bet_total_odd_max'))::text::numeric, 0);
  v_fb bigint := nullif(current_setting('rs.freebet', true), '')::bigint; v_rw public.user_rewards;
begin
  if p_stake is null or p_stake < 1 then raise exception 'Aposta mínima: R$ 1,00'; end if;
  if v_n < 1 then raise exception 'Adicione pelo menos um jogo ao bilhete'; end if;
  if (select count(distinct (e->>'match_id')) from jsonb_array_elements(p_selections) e) <> v_n then
    raise exception 'Só um palpite por jogo';
  end if;

  for v_sel in select * from jsonb_array_elements(p_selections) loop
    select * into v_m from public.matches where id = (v_sel->>'match_id')::bigint for share;
    if not found or v_m.status not in ('open','live') then raise exception 'Jogo indisponível para apostas'; end if;
    if public._suspension(v_m) is not null then
      raise exception 'Apostas suspensas em % (%)', v_m.home || ' x ' || v_m.away, public._suspension(v_m);
    end if;
    v_odd := public._sel_odd(v_m, coalesce(v_sel->>'market', '1x2'), v_sel->>'pick');
    if v_odd is null or v_odd <= 1 then raise exception 'Palpite indisponível em %', v_m.home || ' x ' || v_m.away; end if;
    if v_omin > 0 and v_odd < v_omin then
      raise exception 'Odd mínima por palpite: % (%)', replace(to_char(v_omin, 'FM999990.00'), '.', ','), v_m.home || ' x ' || v_m.away;
    end if;
    v_total := v_total * v_odd;
    v_live := v_live or v_m.status = 'live' or v_m.starts_at <= now();
  end loop;
  -- ao vivo só entra pela confirmação com espera (place_bet_request → place_bet_confirm)
  if v_live and coalesce(current_setting('rs.live_ok', true), '') <> '1' then
    raise exception 'Aposta ao vivo: atualize a página e tente de novo';
  end if;
  if v_live and v_live_max > 0 and p_stake > v_live_max then
    raise exception 'Aposta máxima ao vivo: R$ %', v_live_max;
  end if;
  v_total := round(v_total, 2);
  if v_omax > 0 then v_total := least(v_total, v_omax); end if;

  -- aposta grátis (place_freebet): não sai do saldo e paga só o lucro
  if v_fb is not null then
    select * into v_rw from public.user_rewards where id = v_fb and user_id = v_user and kind = 'freebet' and status = 'disponivel' and expires_at > now() for update;
    if not found or v_rw.amount <> p_stake then raise exception 'Aposta grátis indisponível'; end if;
    if v_total < v_rw.min_odd then raise exception 'Aposta grátis: odd mínima do bilhete %', replace(to_char(v_rw.min_odd, 'FM999990.00'), '.', ','); end if;
  else
    perform public._move(v_user, -p_stake, 'bet', 'Aposta esportiva');
  end if;
  insert into public.bets (user_id, stake, total_odd, potential, freebet_id)
  values (v_user, p_stake, v_total, round(p_stake * v_total, 2) - case when v_fb is null then 0 else p_stake end, v_fb) returning id into v_bet;
  if v_fb is not null then
    insert into public.bet_selections (bet_id, match_id, market, pick, odd)
    select v_bet, m.id, coalesce(e->>'market', '1x2'), e->>'pick', public._sel_odd(m, coalesce(e->>'market', '1x2'), e->>'pick')
    from jsonb_array_elements(p_selections) e join public.matches m on m.id = (e->>'match_id')::bigint;
    update public.user_rewards set status = 'usado', bet_id = v_bet, used_at = now() where id = v_fb;
    return v_bet;
  end if;

  insert into public.bet_selections (bet_id, match_id, market, pick, odd)
  select v_bet, m.id, coalesce(e->>'market', '1x2'), e->>'pick', public._sel_odd(m, coalesce(e->>'market', '1x2'), e->>'pick')
  from jsonb_array_elements(p_selections) e join public.matches m on m.id = (e->>'match_id')::bigint;

  update public.transactions set description = 'Aposta #' || v_bet
   where id = (select max(id) from public.transactions where user_id = v_user and type = 'bet');
  return v_bet;
end $function$;

CREATE OR REPLACE FUNCTION public._resolve_bet(p_bet bigint)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare b public.bets; v_odd numeric;
begin
  select * into b from public.bets where id = p_bet and status = 'pending' for update;
  if not found then return; end if;
  if exists (select 1 from public.bet_selections where bet_id = p_bet and status = 'lost') then
    update public.bets set status = 'lost', settled_at = now() where id = p_bet; return;
  end if;
  if not exists (select 1 from public.bet_selections where bet_id = p_bet and status <> 'canceled') then
    update public.bets set status = 'canceled', potential = b.stake, settled_at = now() where id = p_bet;
    if b.freebet_id is not null then
      update public.user_rewards set status = 'disponivel', bet_id = null, used_at = null where id = b.freebet_id and expires_at > now(); return;
    end if;
    perform public._move(b.user_id, b.stake, 'bet_refund', 'Bilhete #' || p_bet || ' anulado (reembolso)'); return;
  end if;
  select exp(sum(ln(odd))) into v_odd from public.bet_selections where bet_id = p_bet and status <> 'canceled';
  if (select exp(sum(ln(odd))) from public.bet_selections where bet_id = p_bet) > b.total_odd + 0.01 then v_odd := least(v_odd, b.total_odd); end if;
  v_odd := round(b.stake * v_odd, 2) - case when b.freebet_id is null then 0 else b.stake end;
  update public.bets set potential = v_odd where id = p_bet;
  if not exists (select 1 from public.bet_selections where bet_id = p_bet and status = 'pending') then
    update public.bets set status = 'won', settled_at = now() where id = p_bet;
    if v_odd > 0 then perform public._move(b.user_id, v_odd, 'win', 'Prêmio do bilhete #' || p_bet || case when b.freebet_id is null then '' else ' (aposta grátis)' end); end if;
  end if;
end $function$;

CREATE OR REPLACE FUNCTION public.admin_cancel_bets(p_bets bigint[], p_reason text)
 RETURNS integer
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare b public.bets; v_n int := 0;
begin
  perform public._require_perm('sports.manage');
  if length(coalesce(trim(p_reason), '')) < 5 then raise exception 'Informe o motivo'; end if;
  if cardinality(p_bets) > 500 then raise exception 'Máximo de 500 bilhetes por vez'; end if;
  for b in select * from public.bets where id = any(p_bets) and status = 'pending' for update loop
    update public.bets set status = 'canceled', settled_at = now() where id = b.id;
    update public.bet_selections set status = 'canceled' where bet_id = b.id and status = 'pending';
    if b.freebet_id is not null then
      update public.user_rewards set status = 'disponivel', bet_id = null, used_at = null where id = b.freebet_id and expires_at > now();
    else perform public._move(b.user_id, b.stake, 'bet_refund', 'Bilhete #' || b.id || ' cancelado: ' || trim(p_reason)); end if;
    v_n := v_n + 1;
  end loop;
  perform public._audit('bilhetes.cancelar', 'bet', array_to_string(p_bets, ','), p_reason, null, jsonb_build_object('cancelados', v_n));
  return v_n;
end $function$;

CREATE OR REPLACE FUNCTION public.cashout_quote(p_bet bigint)
 RETURNS jsonb
 LANGUAGE plpgsql
 STABLE SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare v_b public.bets; v_factor numeric := 1; r record; v_live boolean := false; v_val numeric;
  v_min numeric := coalesce((public._setting('cashout_min'))::text::numeric, 0);
begin
  select * into v_b from public.bets where id = p_bet and user_id = auth.uid();
  if not found or v_b.status <> 'pending' or v_b.freebet_id is not null then return null; end if;
  for r in select s.status, s.match_id, m.status as m_status, m.starts_at, public._co_odd(m, s.market, s.pick) as now_odd,
                  public._suspension(m) as reason
           from public.bet_selections s join public.matches m on m.id = s.match_id where s.bet_id = p_bet loop
    if r.status = 'lost' then return null; end if;
    if r.status = 'pending' then
      if r.m_status not in ('open','live') then return null; end if;
      if r.reason is not null then return jsonb_build_object('value', null, 'suspended', true, 'reason', r.reason, 'match', r.match_id); end if;
      v_live := v_live or r.m_status = 'live' or r.starts_at <= now();
      if r.now_odd is null or r.now_odd <= 1 then
        return jsonb_build_object('value', null, 'suspended', true, 'reason', 'Mercado indisponível', 'match', r.match_id);
      end if;
      v_factor := v_factor / r.now_odd;
    end if;
  end loop;
  v_val := least(round(v_b.potential * v_factor * case when v_live then 0.92 else 0.95 end, 2), v_b.potential);
  -- abaixo do mínimo (cashout_min): indisponível, mas mostra o valor atual e o mínimo
  if v_min > 0 and v_val < v_min then
    return jsonb_build_object('value', null, 'suspended', true, 'reason', 'Abaixo do mínimo', 'now', v_val, 'min', v_min);
  end if;
  return jsonb_build_object('value', v_val, 'suspended', false, 'live', v_live);
end $function$;

CREATE OR REPLACE FUNCTION public._cashout_pay(p_bet bigint, p_user uuid, p_val numeric)
 RETURNS numeric
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
begin
  if (select freebet_id from public.bets where id = p_bet) is not null then raise exception 'Cashout indisponível em aposta grátis'; end if;
  update public.bets set status = 'cashout', cashout_amount = p_val, settled_at = now() where id = p_bet;
  perform public._move(p_user, p_val, 'cashout', 'Cashout do bilhete #' || p_bet);
  return p_val;
end $function$;

CREATE OR REPLACE FUNCTION public._bonus_on_bet()
 RETURNS trigger
 LANGUAGE plpgsql
