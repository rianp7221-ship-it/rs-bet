-- ---------- prêmios do jogador ----------
create table if not exists public.user_rewards (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  kind text not null check (kind in ('freebet','freespins')),
  title text not null,
  amount numeric(14,2) not null check (amount > 0),          -- freebet: valor; freespins: valor de cada rodada
  spins int not null default 0, spins_left int not null default 0,
  game_id text, game_name text,
  won numeric(14,2) not null default 0, max_win numeric(14,2),
  min_odd numeric(6,2) not null default 1,
  status text not null default 'disponivel' check (status in ('disponivel','em_uso','usado','expirado')),
  source text, bet_id bigint,
  expires_at timestamptz not null, created_at timestamptz not null default now(), used_at timestamptz
);
create index if not exists user_rewards_user_idx on public.user_rewards (user_id, status);
alter table public.user_rewards enable row level security;
drop policy if exists user_rewards_read on public.user_rewards;
create policy user_rewards_read on public.user_rewards for select using (user_id = auth.uid() or public.has_perm('bonus.view'));

create table if not exists public.wheel_spins (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  day date not null, idx int not null, label text not null, reward_id bigint,
  created_at timestamptz not null default now(),
  unique (user_id, day)
);
alter table public.wheel_spins enable row level security;
drop policy if exists wheel_spins_read on public.wheel_spins;
create policy wheel_spins_read on public.wheel_spins for select using (user_id = auth.uid() or public.has_perm('bonus.view'));

alter table public.bets add column if not exists freebet_id bigint;
alter table public.casino_tx add column if not exists free_reward bigint;

create or replace function public._today() returns date language sql stable as $$ select (now() at time zone 'America/Sao_Paulo')::date $$;

create or replace function public._expire_rewards(p_user uuid) returns void
language sql security definer set search_path = public as $$
  update public.user_rewards set status = 'expirado' where user_id = p_user and status in ('disponivel','em_uso') and expires_at <= now()
$$;

create or replace function public._grant_reward(p_user uuid, p_kind text, p_value numeric, p_title text, p_source text) returns bigint
language plpgsql security definer set search_path = public as $$
declare v_id bigint; v_days int := coalesce((public._setting('reward_days'))::text::int, 7);
  v_sv numeric := coalesce((public._setting('freespin_value'))::text::numeric, 0.10);
begin
  if p_kind = 'freebet' then
    insert into public.user_rewards (user_id, kind, title, amount, min_odd, source, expires_at)
    values (p_user, 'freebet', p_title, p_value, coalesce((public._setting('freebet_min_odd'))::text::numeric, 1.5), p_source, now() + make_interval(days => v_days))
    returning id into v_id;
  else
    insert into public.user_rewards (user_id, kind, title, amount, spins, spins_left, max_win, source, expires_at)
    values (p_user, 'freespins', p_title, v_sv, p_value::int, p_value::int, coalesce((public._setting('freespin_max_win'))::text::numeric, 50), p_source,
            now() + make_interval(days => v_days))
    returning id into v_id;
  end if;
  insert into public.notifications (user_id, title, body) values (p_user, 'Você ganhou: ' || p_title,
    case when p_kind = 'freebet' then format('Use em Minha conta → Bônus ou no bilhete. Odd mínima %s, válida por %s dias. O lucro vai para o saldo, sem rollover.',
      coalesce((public._setting('freebet_min_odd'))::text, '1.5'), v_days)
    else format('Escolha o jogo em Minha conta → Bônus. Rodadas de R$ %s, válidas por %s dias. O que ganhar vai para o saldo, sem rollover.', v_sv, v_days) end);
  return v_id;
end $$;

-- ---------- roleta ----------
create or replace function public._wheel_bet_today(p_user uuid) returns numeric
language sql stable security definer set search_path = public as $$
  select coalesce(sum(stake), 0) from public.bets
   where user_id = p_user and freebet_id is null and status <> 'canceled'
     and created_at >= (public._today()::timestamp at time zone 'America/Sao_Paulo')
$$;

create or replace function public.wheel_status() returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare v_user uuid := auth.uid(); v_min numeric := coalesce((public._setting('wheel_min_bet'))::text::numeric, 10);
  v_bet numeric := 0; s public.wheel_spins;
begin
  if v_user is not null then
    v_bet := public._wheel_bet_today(v_user);
    select * into s from public.wheel_spins where user_id = v_user and day = public._today();
  end if;
  return jsonb_build_object('on', coalesce((public._setting('wheel_on'))::text::boolean, true),
    'prizes', (select jsonb_agg(e->>'label' order by o) from jsonb_array_elements(public._setting('wheel_prizes')) with ordinality t(e, o)),
    'logged', v_user is not null, 'min', v_min, 'bet', v_bet, 'spun', s.id is not null, 'idx', s.idx, 'label', s.label);
end $$;

create or replace function public.wheel_spin() returns jsonb
language plpgsql security definer set search_path = public as $$
declare v_user uuid := public._me(); v_pr jsonb := public._setting('wheel_prizes'); v_min numeric := coalesce((public._setting('wheel_min_bet'))::text::numeric, 10);
  v_tot numeric; v_r numeric; v_acc numeric := 0; v_idx int; e jsonb; o bigint; v_rw bigint; l public.user_limits;
begin
  if not coalesce((public._setting('wheel_on'))::text::boolean, true) then raise exception 'A roleta está desligada no momento'; end if;
  l := public._limits(v_user);
  if l.self_excluded_until > now() then raise exception 'Conta pausada'; end if;
  perform 1 from public.profiles where id = v_user for update;
  if exists (select 1 from public.wheel_spins where user_id = v_user and day = public._today()) then raise exception 'Você já girou hoje. Volte amanhã!'; end if;
  if public._wheel_bet_today(v_user) < v_min then
    raise exception 'Aposte R$ % hoje para liberar o giro', replace(to_char(v_min, 'FM999990.00'), '.', ',');
  end if;
  select sum((x->>'w')::numeric) into v_tot from jsonb_array_elements(v_pr) x;
  v_r := random() * v_tot;
  for e, o in select x, n from jsonb_array_elements(v_pr) with ordinality t(x, n) loop
    v_acc := v_acc + (e->>'w')::numeric;
    if v_r < v_acc then v_idx := o - 1; exit; end if;
  end loop;
  if v_idx is null then v_idx := jsonb_array_length(v_pr) - 1; end if;
  e := v_pr->v_idx;
  if e->>'kind' in ('freebet','freespins') then
    v_rw := public._grant_reward(v_user, e->>'kind', (e->>'value')::numeric, e->>'label', 'roleta:' || public._today());
  end if;
  insert into public.wheel_spins (user_id, day, idx, label, reward_id) values (v_user, public._today(), v_idx, e->>'label', v_rw);
  return jsonb_build_object('idx', v_idx, 'label', e->>'label', 'kind', e->>'kind', 'reward', v_rw);
end $$;

-- ---------- rodadas grátis: jogos do dia ----------
create or replace function public.freespin_games() returns setof public.casino_catalog
language plpgsql stable security definer set search_path = public as $$
declare v_fix jsonb := coalesce(public._setting('freespin_games'), '[]');
begin
  if jsonb_array_length(v_fix) > 0 then
    return query select c.* from public.casino_catalog c where c.active and c.id in (select jsonb_array_elements_text(v_fix)) limit 5;
    return;
  end if;
  -- Pragmatic de até 10 linhas (aposta mínima costuma ser R$ 0,05–0,10), sorteados por dia
  return query select c.* from public.casino_catalog c
    where c.active and c.pf_provider = 'PRAGMATIC' and c.image is not null and c.pf_code ~ '^vs([1-9]|10)[a-z]'
    order by md5(c.id || public._today()::text) limit 5;
end $$;

create or replace function public.freespin_pick(p_reward bigint, p_game text) returns jsonb
language plpgsql security definer set search_path = public as $$
declare v_user uuid := public._me(); r public.user_rewards; g public.casino_catalog;
begin
  perform public._expire_rewards(v_user);
  select * into r from public.user_rewards where id = p_reward and user_id = v_user and kind = 'freespins' for update;
  if not found or r.status not in ('disponivel','em_uso') then raise exception 'Rodadas grátis indisponíveis'; end if;
  if r.status = 'em_uso' and r.spins_left < r.spins then
    if r.game_id <> p_game then raise exception 'Termine as rodadas em %', r.game_name; end if;
    return jsonb_build_object('game', r.game_id);
  end if;
  select * into g from public.freespin_games() f where f.id = p_game;
  if not found then raise exception 'Escolha um jogo da lista de hoje'; end if;
  -- só um pacote em uso por vez
  update public.user_rewards set status = 'disponivel', game_id = null, game_name = null
   where user_id = v_user and kind = 'freespins' and status = 'em_uso' and spins_left = spins and id <> r.id;
  if exists (select 1 from public.user_rewards where user_id = v_user and kind = 'freespins' and status = 'em_uso' and id <> r.id) then
    raise exception 'Termine as rodadas grátis que você já começou';
  end if;
  update public.user_rewards set status = 'em_uso', game_id = g.id, game_name = g.name where id = r.id;
  return jsonb_build_object('game', g.id);
end $$;

create or replace function public._pf_free_credit(p_user uuid) returns numeric
language sql stable security definer set search_path = public as $$
  select coalesce(sum(spins_left * amount), 0) from public.user_rewards
   where user_id = p_user and kind = 'freespins' and status = 'em_uso' and spins_left > 0 and expires_at > now()
$$;

-- ---------- mais apostado do dia ----------
create or replace function public.top_pick_today() returns jsonb
language sql stable security definer set search_path = public as $$
  with sel as (
    select s.match_id, s.market, s.pick, count(*) n from public.bet_selections s join public.bets b on b.id = s.bet_id
     where b.created_at >= now() - interval '24 hours' and b.status <> 'canceled' and s.market = '1x2'
     group by 1, 2, 3),
  top as (
    select sel.*, sum(n) over (partition by sel.match_id, sel.market) tot, sum(n) over (partition by sel.match_id) mtot
      from sel join public.matches m on m.id = sel.match_id
     where m.status = 'open' and m.starts_at > now() and public._suspension(m) is null
       and coalesce(public._sel_odd(m, sel.market, sel.pick), 0) > 1)
  select jsonb_build_object('match', m.id, 'home', m.home, 'away', m.away, 'league', m.league, 'starts_at', m.starts_at,
           'home_logo', m.home_logo, 'away_logo', m.away_logo, 'market', t.market, 'pick', t.pick, 'bets', t.mtot,
           'pct', round(100.0 * t.n / t.tot), 'odd', public._sel_odd(m, t.market, t.pick))
    from top t join public.matches m on m.id = t.match_id
   order by t.mtot desc, t.n desc limit 1
$$;

