create or replace function public.place_freebet(p_selections jsonb, p_reward bigint) returns bigint
language plpgsql security definer set search_path = public as $$
declare v_user uuid := public._me(); r public.user_rewards; v_q jsonb := public._bet_quote(p_selections); v_bet bigint;
begin
  perform public._expire_rewards(v_user);
  select * into r from public.user_rewards where id = p_reward and user_id = v_user and kind = 'freebet' for update;
  if not found or r.status <> 'disponivel' then raise exception 'Aposta grátis indisponível'; end if;
  if v_q ? 'error' then raise exception '%', v_q->>'error'; end if;
  if (v_q->>'live')::boolean then raise exception 'Aposta grátis só em jogos que ainda não começaram'; end if;
  perform set_config('rs.freebet', r.id::text, true);
  v_bet := public.place_bet(p_selections, r.amount);
  perform set_config('rs.freebet', '', true);
  return v_bet;
end $$;

