-- master (is_admin ou cargo master) tem tudo; os outros cargos só o que está em role_permissions
create or replace function public.has_perm(p_perm text) returns boolean
language sql stable security definer set search_path = public as $$
  select coalesce(auth.role(), '') = 'service_role' or exists (
    select 1 from public.profiles p
    where p.id = auth.uid() and not p.blocked
      and (p.is_admin or p.staff_role = 'master'
           or exists (select 1 from public.role_permissions r where r.role = p.staff_role and r.perm = p_perm))
      and (not coalesce((public._setting('require_admin_mfa'))::text::boolean, false)
           or coalesce(auth.jwt() ->> 'aal', '') = 'aal2'))
$$;

create or replace function public._require_perm(p_perm text) returns void
language plpgsql stable security definer set search_path = public as $$
begin
  if not public.has_perm(p_perm) then raise exception 'Sem permissão para esta ação (%)', p_perm; end if;
end $$;

create or replace function public._require_admin() returns void
language plpgsql stable security definer set search_path = public as $$
