create or replace function public.settle_match(p_match bigint, p_result text) returns void
language plpgsql security definer set search_path = public as $$
declare r record; v_m public.matches;
begin
  perform public._require_perm('sports.manage');
  if p_result not in ('home','draw','away') then raise exception 'Resultado inválido'; end if;
  update public.matches set status = 'settled', result = p_result where id = p_match and status <> 'settled' returning * into v_m;
  if not found then raise exception 'Jogo não encontrado ou já liquidado'; end if;
  update public.bet_selections set status = case when pick = p_result then 'won' else 'lost' end
   where match_id = p_match and status = 'pending';
  for r in select b.* from public.bets b
           where b.status = 'pending' and exists (select 1 from public.bet_selections s where s.bet_id = b.id and s.match_id = p_match)
           for update loop
    if exists (select 1 from public.bet_selections where bet_id = r.id and status = 'lost') then
      update public.bets set status = 'lost', settled_at = now() where id = r.id;
    elsif not exists (select 1 from public.bet_selections where bet_id = r.id and status = 'pending') then
      update public.bets set status = 'won', settled_at = now() where id = r.id;
      perform public._move(r.user_id, r.potential, 'win', 'Prêmio do bilhete #' || r.id);
    end if;
  end loop;
  perform public._audit('jogo.liquidar', 'match', p_match::text, null, null,
                        jsonb_build_object('jogo', v_m.home || ' x ' || v_m.away, 'resultado', p_result));
end $$;

create or replace function public.admin_review_transaction(p_tx bigint, p_approve boolean) returns void
language plpgsql security definer set search_path = public as $$
declare v_t public.transactions;
begin
  perform public._require_perm('finance.manage');
  select * into v_t from public.transactions where id = p_tx and status = 'pending' for update;
  if not found then raise exception 'Transação não está pendente'; end if;
  update public.transactions set status = case when p_approve then 'done' else 'rejected' end where id = p_tx;
  if v_t.type = 'deposit' and p_approve then
    update public.profiles set balance = balance + v_t.amount where id = v_t.user_id;
  elsif v_t.type = 'withdraw' and not p_approve then
    perform public._move(v_t.user_id, abs(v_t.amount), 'refund', 'Saque #' || p_tx || ' recusado');
  end if;
  perform public._audit(case when p_approve then 'financeiro.aprovar' else 'financeiro.recusar' end, 'transaction', p_tx::text, null,
                        to_jsonb(v_t), jsonb_build_object('status', case when p_approve then 'done' else 'rejected' end));
end $$;

create or replace function public.admin_adjust_balance(p_user uuid, p_amount numeric, p_reason text) returns void
language plpgsql security definer set search_path = public as $$
declare v_before numeric;
begin
  perform public._require_perm('users.balance');
  if length(coalesce(trim(p_reason), '')) < 5 then raise exception 'Informe o motivo do ajuste'; end if;
  if p_amount is null or p_amount = 0 then raise exception 'Valor inválido'; end if;
  select balance into v_before from public.profiles where id = p_user for update;
  if not found then raise exception 'Usuário não encontrado'; end if;
  perform public._move(p_user, round(p_amount, 2), 'adjust', 'Ajuste: ' || trim(p_reason));
  perform public._audit('usuario.ajuste_saldo', 'profile', p_user::text, p_reason,
                        jsonb_build_object('balance', v_before), jsonb_build_object('balance', v_before + round(p_amount, 2)));
end $$;

drop function if exists public.admin_set_blocked(uuid, boolean);
create or replace function public.admin_set_blocked(p_user uuid, p_blocked boolean, p_reason text default null) returns void
language plpgsql security definer set search_path = public as $$
declare v_old boolean;
begin
  perform public._require_perm('users.block');
  if p_blocked and length(coalesce(trim(p_reason), '')) < 5 then raise exception 'Informe o motivo do bloqueio'; end if;
  if p_user = auth.uid() then raise exception 'Você não pode bloquear a sua própria conta'; end if;
  select blocked into v_old from public.profiles where id = p_user for update;
  if not found then raise exception 'Usuário não encontrado'; end if;
  update public.profiles set blocked = p_blocked where id = p_user;
  perform public._audit(case when p_blocked then 'usuario.bloquear' else 'usuario.desbloquear' end, 'profile', p_user::text, p_reason,
                        jsonb_build_object('blocked', v_old), jsonb_build_object('blocked', p_blocked));
end $$;

-- trava manual / status do jogo pelo painel
create or replace function public.admin_match_set(p_match bigint, p_locked boolean default null, p_status text default null) returns void
language plpgsql security definer set search_path = public as $$
declare v_m public.matches;
begin
  perform public._require_perm('sports.manage');
  if p_status is not null and p_status not in ('open','live','closed') then raise exception 'Status inválido'; end if;
  select * into v_m from public.matches where id = p_match for update;
  if not found then raise exception 'Jogo não encontrado'; end if;
  update public.matches set locked = coalesce(p_locked, locked), status = coalesce(p_status, status) where id = p_match;
  perform public._audit('jogo.alterar', 'match', p_match::text, null,
                        jsonb_build_object('jogo', v_m.home || ' x ' || v_m.away, 'locked', v_m.locked, 'status', v_m.status),
                        jsonb_build_object('locked', coalesce(p_locked, v_m.locked), 'status', coalesce(p_status, v_m.status)));
end $$;

-- jogos criados/excluídos manualmente no painel ficam na auditoria
