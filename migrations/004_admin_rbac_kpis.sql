-- aposta muito acima do normal do jogador ou retorno possível alto
create or replace function public._bet_alerts() returns trigger
language plpgsql security definer set search_path = public as $$
declare v_avg numeric;
begin
  select avg(stake) into v_avg from public.bets
   where user_id = new.user_id and id <> new.id and created_at > now() - interval '30 days';
  if new.stake >= coalesce((public._setting('alert_big_bet'))::text::numeric, 500)
     and (v_avg is null or new.stake > 5 * v_avg) then
    perform public._alert('aposta_alta', 'alta', new.user_id, 'bet:' || new.id,
      format('Aposta de R$ %s no bilhete #%s (média do jogador: %s)', new.stake, new.id,
             coalesce('R$ ' || round(v_avg, 2), 'sem histórico')));
  end if;
  if new.potential >= coalesce((public._setting('alert_big_return'))::text::numeric, 10000) then
    perform public._alert('retorno_alto', 'critica', new.user_id, 'bet:' || new.id,
      format('Bilhete #%s pode pagar R$ %s (odd %s)', new.id, new.potential, new.total_odd));
  end if;
  return null;
end $$;
drop trigger if exists bet_alerts on public.bets;
create trigger bet_alerts after insert on public.bets for each row execute function public._bet_alerts();

-- saque logo depois de depósito sem apostar o valor (possível lavagem)
create or replace function public._tx_alerts() returns trigger
language plpgsql security definer set search_path = public as $$
declare v_dep public.transactions; v_bet numeric;
begin
  if new.type = 'withdraw' then
    select * into v_dep from public.transactions
     where user_id = new.user_id and type = 'deposit' and status = 'done' and created_at > now() - interval '48 hours'
     order by created_at desc limit 1;
    if found then
      select coalesce(-sum(amount), 0) into v_bet from public.transactions
       where user_id = new.user_id and type in ('bet','casino_bet') and status = 'done' and created_at >= v_dep.created_at;
      if v_bet < v_dep.amount then
        perform public._alert('saque_sem_giro', 'alta', new.user_id, 'tx:' || new.id,
          format('Saque de R$ %s pouco depois de depósito de R$ %s, com só R$ %s apostados', abs(new.amount), v_dep.amount, v_bet));
      end if;
    end if;
  end if;
  return null;
end $$;
drop trigger if exists tx_alerts on public.transactions;
create trigger tx_alerts after insert on public.transactions for each row execute function public._tx_alerts();

-- varredura periódica: saldo diferente do extrato e várias contas no mesmo palpite
create or replace function public._scan_alerts() returns void
language plpgsql security definer set search_path = public as $$
declare r record;
begin
  for r in select p.id, p.email, p.balance,
                  coalesce(sum(t.amount) filter (where t.status = 'done' or (t.type = 'withdraw' and t.status = 'pending')), 0) as ledger
           from public.profiles p left join public.transactions t on t.user_id = p.id
           group by p.id loop
    if r.balance <> r.ledger then
      perform public._alert('saldo_divergente', 'critica', r.id, 'user:' || r.id,
        format('Saldo de %s (R$ %s) diferente do extrato (R$ %s)', r.email, r.balance, r.ledger));
    end if;
  end loop;
  for r in select s.match_id, s.pick, m.home, m.away, count(distinct b.user_id) as n, sum(b.stake) as total
           from public.bet_selections s join public.bets b on b.id = s.bet_id join public.matches m on m.id = s.match_id
           where b.created_at > now() - interval '15 minutes'
           group by 1, 2, 3, 4 having count(distinct b.user_id) >= 5 and sum(b.stake) >= 2000 loop
    perform public._alert('concentracao', 'alta', null, 'match:' || r.match_id || ':' || r.pick,
      format('%s contas apostaram R$ %s em %s x %s (palpite %s) nos últimos 15 min', r.n, r.total, r.home, r.away, r.pick));
  end loop;
end $$;

do $$ begin
  if exists (select 1 from pg_extension where extname = 'pg_cron') then
    perform cron.schedule('scan-alerts', '*/10 * * * *', 'select public._scan_alerts()');
  end if;
end $$;

create or replace function public.admin_alert_update(p_id bigint, p_status text, p_resolution text default null) returns void
language plpgsql security definer set search_path = public as $$
declare v_before jsonb;
begin
  perform public._require_perm('alerts.manage');
  if p_status not in ('aberto','em_analise','resolvido') then raise exception 'Status inválido'; end if;
  select to_jsonb(a) into v_before from public.alerts a where id = p_id for update;
  if v_before is null then raise exception 'Alerta não encontrado'; end if;
  if p_status = 'resolvido' and coalesce(trim(p_resolution), '') = '' then raise exception 'Descreva como o alerta foi resolvido'; end if;
  update public.alerts set status = p_status,
         assigned_to = case when p_status = 'em_analise' then auth.uid() else assigned_to end,
         resolution = coalesce(nullif(trim(p_resolution), ''), resolution),
         resolved_at = case when p_status = 'resolvido' then now() end
   where id = p_id;
  perform public._audit('alerta.' || p_status, 'alert', p_id::text, p_resolution, v_before,
                        (select to_jsonb(a) from public.alerts a where id = p_id));
end $$;

