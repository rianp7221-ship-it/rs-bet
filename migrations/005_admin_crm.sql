create table if not exists public.user_limits (
  user_id uuid primary key references public.profiles(id) on delete cascade,
  deposit_day numeric(14,2), deposit_week numeric(14,2), deposit_month numeric(14,2),
  loss_day numeric(14,2), self_excluded_until timestamptz,
  pending jsonb, pending_at timestamptz,
  updated_at timestamptz not null default now()
);

-- aplica aumentos de limite que já cumpriram as 24 h de espera
create or replace function public._limits(p_user uuid) returns public.user_limits
language plpgsql security definer set search_path = public as $$
declare l public.user_limits;
begin
  select * into l from public.user_limits where user_id = p_user;
  if found and l.pending is not null and l.pending_at <= now() then
    update public.user_limits set
      deposit_day = case when l.pending ? 'deposit_day' then (l.pending->>'deposit_day')::numeric else deposit_day end,
      deposit_week = case when l.pending ? 'deposit_week' then (l.pending->>'deposit_week')::numeric else deposit_week end,
      deposit_month = case when l.pending ? 'deposit_month' then (l.pending->>'deposit_month')::numeric else deposit_month end,
      loss_day = case when l.pending ? 'loss_day' then (l.pending->>'loss_day')::numeric else loss_day end,
      pending = null, pending_at = null, updated_at = now()
    where user_id = p_user returning * into l;
  end if;
  return l;
end $$;

-- jogador: reduzir vale na hora; aumentar ou remover vale depois de 24 h
create or replace function public.set_my_limits(p_deposit_day numeric, p_deposit_week numeric, p_deposit_month numeric,
                                                p_loss_day numeric, p_exclude_days int default null) returns jsonb
language plpgsql security definer set search_path = public as $$
declare v_user uuid := public._me(); l public.user_limits; v_now jsonb := '{}'; v_later jsonb := '{}'; k text; v_new numeric; v_old numeric;
begin
  insert into public.user_limits (user_id) values (v_user) on conflict do nothing;
  l := public._limits(v_user);
  foreach k in array array['deposit_day','deposit_week','deposit_month','loss_day'] loop
    v_new := case k when 'deposit_day' then p_deposit_day when 'deposit_week' then p_deposit_week
                    when 'deposit_month' then p_deposit_month else p_loss_day end;
    if v_new is not null and v_new <= 0 then v_new := null; end if;
    v_old := (to_jsonb(l) ->> k)::numeric;
    if v_new is not distinct from v_old then continue; end if;
    if v_new is not null and (v_old is null or v_new < v_old) then v_now := v_now || jsonb_build_object(k, v_new);
    else v_later := v_later || jsonb_build_object(k, v_new); end if;
  end loop;
  update public.user_limits set
    deposit_day = case when v_now ? 'deposit_day' then (v_now->>'deposit_day')::numeric else deposit_day end,
    deposit_week = case when v_now ? 'deposit_week' then (v_now->>'deposit_week')::numeric else deposit_week end,
    deposit_month = case when v_now ? 'deposit_month' then (v_now->>'deposit_month')::numeric else deposit_month end,
    loss_day = case when v_now ? 'loss_day' then (v_now->>'loss_day')::numeric else loss_day end,
    pending = case when v_later = '{}' then pending else coalesce(pending, '{}') || v_later end,
    pending_at = case when v_later = '{}' then pending_at else now() + interval '24 hours' end,
    self_excluded_until = case when coalesce(p_exclude_days, 0) > 0
                               then greatest(coalesce(self_excluded_until, now()), now() + make_interval(days => p_exclude_days))
                               else self_excluded_until end,
    updated_at = now()
  where user_id = v_user;
  return jsonb_build_object('aplicado', v_now, 'em_24h', v_later);
end $$;

create or replace function public.admin_set_limits(p_user uuid, p_deposit_day numeric, p_deposit_week numeric, p_deposit_month numeric,
                                                   p_loss_day numeric, p_excluded_until timestamptz, p_reason text) returns void
language plpgsql security definer set search_path = public as $$
declare v_before jsonb;
begin
  perform public._require_perm('users.limits');
  if length(coalesce(trim(p_reason), '')) < 5 then raise exception 'Informe o motivo'; end if;
  insert into public.user_limits (user_id) values (p_user) on conflict do nothing;
  select to_jsonb(l) into v_before from public.user_limits l where user_id = p_user for update;
  update public.user_limits set deposit_day = nullif(p_deposit_day, 0), deposit_week = nullif(p_deposit_week, 0),
         deposit_month = nullif(p_deposit_month, 0), loss_day = nullif(p_loss_day, 0),
         self_excluded_until = p_excluded_until, pending = null, pending_at = null, updated_at = now()
   where user_id = p_user;
  perform public._audit('usuario.limites', 'profile', p_user::text, p_reason, v_before,
                        (select to_jsonb(l) from public.user_limits l where user_id = p_user));
end $$;

-- autoexclusão bloqueia jogar; limite de perda diária vale para esportes e cassino
create or replace function public._check_play(p_user uuid, p_stake numeric) returns void
language plpgsql security definer set search_path = public as $$
declare l public.user_limits; v_loss numeric;
begin
  l := public._limits(p_user);
  if l.user_id is null then return; end if;
  if l.self_excluded_until > now() then
    raise exception 'Conta em pausa até %', to_char(l.self_excluded_until at time zone 'America/Sao_Paulo', 'DD/MM/YYYY HH24:MI');
  end if;
  if l.loss_day is not null then
    select coalesce(-sum(amount), 0) into v_loss from public.transactions
     where user_id = p_user and status = 'done' and type in ('bet','casino_bet','win','cashout','casino_win','bet_refund')
       and created_at >= date_trunc('day', now() at time zone 'America/Sao_Paulo') at time zone 'America/Sao_Paulo';
    if v_loss + p_stake > l.loss_day then
      raise exception 'Limite diário de perda atingido (R$ %)', l.loss_day;
    end if;
  end if;
end $$;

create or replace function public._move(p_user uuid, p_amount numeric, p_type text, p_desc text) returns void
language plpgsql security definer set search_path = public as $$
begin
  if p_type in ('bet','casino_bet') then perform public._check_play(p_user, -p_amount); end if;
  update public.profiles set balance = balance + p_amount
   where id = p_user and balance + p_amount >= 0;
  if not found then raise exception 'Saldo insuficiente'; end if;
  insert into public.transactions (user_id, type, amount, status, description)
  values (p_user, p_type, p_amount, 'done', p_desc);
end $$;

create or replace function public.request_deposit(p_amount numeric) returns bigint
language plpgsql security definer set search_path = public as $$
declare v_user uuid := public._me(); v_id bigint; l public.user_limits; v_sum numeric;
begin
  if p_amount is null or p_amount < 10 then raise exception 'Depósito mínimo: R$ 10,00'; end if;
  l := public._limits(v_user);
  if l.user_id is not null then
    if l.self_excluded_until > now() then raise exception 'Conta em pausa: depósitos bloqueados'; end if;
    select coalesce(sum(amount) filter (where created_at > now() - interval '1 day'), 0) into v_sum from public.transactions
     where user_id = v_user and type = 'deposit' and status in ('pending','done');
    if l.deposit_day is not null and v_sum + p_amount > l.deposit_day then raise exception 'Limite diário de depósito: R$ %', l.deposit_day; end if;
    select coalesce(sum(amount), 0) into v_sum from public.transactions
     where user_id = v_user and type = 'deposit' and status in ('pending','done') and created_at > now() - interval '7 days';
    if l.deposit_week is not null and v_sum + p_amount > l.deposit_week then raise exception 'Limite semanal de depósito: R$ %', l.deposit_week; end if;
    select coalesce(sum(amount), 0) into v_sum from public.transactions
     where user_id = v_user and type = 'deposit' and status in ('pending','done') and created_at > now() - interval '30 days';
    if l.deposit_month is not null and v_sum + p_amount > l.deposit_month then raise exception 'Limite mensal de depósito: R$ %', l.deposit_month; end if;
  end if;
  insert into public.transactions (user_id, type, amount, status, description)
  values (v_user, 'deposit', round(p_amount, 2), 'pending', 'Depósito PIX') returning id into v_id;
  return v_id;
end $$;

