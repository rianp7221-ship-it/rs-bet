create or replace function public.admin_search_users(p_q text default null, p_status text default null, p_risk text default null,
  p_min_balance numeric default null, p_max_balance numeric default null, p_country text default null,
  p_limit int default 50, p_offset int default 0) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare v jsonb;
begin
  perform public._require_perm('users.view');
  with base as (
    select p.*,
      (select coalesce(sum(amount), 0) from public.transactions t where t.user_id = p.id and t.type = 'deposit' and t.status = 'done') as deposits,
      (select count(*) from public.bets b where b.user_id = p.id) as bets_count,
      (select l.self_excluded_until > now() from public.user_limits l where l.user_id = p.id) as excluded
    from public.profiles p
    where (p_q is null or p_q = '' or p.email ilike '%' || p_q || '%' or p.username ilike '%' || p_q || '%' or p.id::text = p_q or p.last_ip = p_q)
      and (p_status is null or p_status = '' or (p_status = 'bloqueado' and p.blocked) or (p_status = 'ativo' and not p.blocked)
           or (p_status = 'equipe' and (p.is_admin or p.staff_role is not null)))
      and (p_risk is null or p_risk = '' or p.risk_level = p_risk)
      and (p_min_balance is null or p.balance >= p_min_balance)
      and (p_max_balance is null or p.balance <= p_max_balance)
      and (p_country is null or p_country = '' or p.country = upper(p_country)))
  select jsonb_build_object('total', (select count(*) from base),
    'rows', coalesce((select jsonb_agg(to_jsonb(x) - 'is_admin') from (select id, email, username, balance, blocked, risk_level, country, staff_role,
                       is_admin, created_at, last_login_at, last_ip, deposits, bets_count, coalesce(excluded, false) as excluded
                     from base order by created_at desc limit least(p_limit, 200) offset p_offset) x), '[]'))
  into v;
  return v;
end $$;

create or replace function public.admin_user_profile(p_user uuid) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare v_p public.profiles;
begin
  perform public._require_perm('users.view');
  select * into v_p from public.profiles where id = p_user;
  if not found then raise exception 'Usuário não encontrado'; end if;
  return jsonb_build_object(
    'profile', to_jsonb(v_p),
    'totals', (select jsonb_build_object(
        'deposits', coalesce(sum(amount) filter (where type = 'deposit' and status = 'done'), 0),
        'withdrawals', coalesce(-sum(amount) filter (where type = 'withdraw' and status = 'done'), 0),
        'staked', coalesce(-sum(amount) filter (where type in ('bet','casino_bet') and status = 'done'), 0),
        'won', coalesce(sum(amount) filter (where type in ('win','cashout','casino_win','bet_refund') and status = 'done'), 0),
        'adjust', coalesce(sum(amount) filter (where type = 'adjust' and status = 'done'), 0),
        'method', 'PIX') from public.transactions where user_id = p_user),
    'limits', (select to_jsonb(l) from public.user_limits l where user_id = p_user),
    'devices', coalesce((select jsonb_agg(to_jsonb(d) order by d.created_at desc) from (select * from public.device_logs where user_id = p_user order by created_at desc limit 30) d), '[]'),
    'linked', coalesce((select jsonb_agg(distinct jsonb_build_object('id', p.id, 'email', p.email, 'blocked', p.blocked))
                        from public.device_logs d join public.profiles p on p.id = d.user_id
                        where d.user_id <> p_user and exists (select 1 from public.device_logs me where me.user_id = p_user
                          and ((me.fingerprint is not null and me.fingerprint = d.fingerprint) or (me.ip is not null and me.ip = d.ip)))), '[]'),
    'notes', coalesce((select jsonb_agg(to_jsonb(n) order by n.created_at desc) from public.user_notes n where n.user_id = p_user), '[]'),
    'alerts', (select count(*) from public.alerts where user_id = p_user and status <> 'resolvido'));
end $$;

