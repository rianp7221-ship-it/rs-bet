create or replace function public._req_header(p_name text) returns text
language sql stable as $$
  select nullif(current_setting('request.headers', true), '')::json ->> p_name
$$;

-- chamado pelo site uma vez por sessão; detecta contas no mesmo dispositivo/IP
create or replace function public.log_login(p_fingerprint text) returns void
language plpgsql security definer set search_path = public as $$
declare
  v_user uuid := auth.uid();
  v_ip text := split_part(coalesce(public._req_header('x-forwarded-for'), ''), ',', 1);
  v_fp text := left(nullif(trim(p_fingerprint), ''), 128);
  v_others text;
begin
  if v_user is null then return; end if;
  if exists (select 1 from public.device_logs where user_id = v_user and created_at > now() - interval '30 minutes'
             and coalesce(fingerprint, '') = coalesce(v_fp, '') and coalesce(ip, '') = coalesce(v_ip, '')) then return; end if;
  insert into public.device_logs (user_id, ip, user_agent, fingerprint)
  values (v_user, nullif(v_ip, ''), left(public._req_header('user-agent'), 300), v_fp);
  update public.profiles set last_login_at = now(), last_ip = nullif(v_ip, '') where id = v_user;
  select string_agg(distinct p.email, ', ') into v_others
  from public.device_logs d join public.profiles p on p.id = d.user_id
  where d.user_id <> v_user and d.created_at > now() - interval '30 days'
    and ((v_fp is not null and d.fingerprint = v_fp) or (nullif(v_ip, '') is not null and d.ip = v_ip));
  if v_others is not null then
    perform public._alert('multi_conta', 'alta', v_user, 'user:' || v_user,
      format('%s usa o mesmo dispositivo ou IP que: %s', (select email from public.profiles where id = v_user), v_others));
  end if;
end $$;

-- ---------- NOTIFICAÇÕES IN-APP ----------
create table if not exists public.notifications (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  title text not null, body text, read_at timestamptz, created_by uuid,
  created_at timestamptz not null default now()
);
create index if not exists notifications_user_idx on public.notifications (user_id, created_at desc);

create or replace function public.admin_send_notification(p_user uuid, p_title text, p_body text) returns int
language plpgsql security definer set search_path = public as $$
declare v_n int;
begin
  perform public._require_perm('users.message');
  if length(coalesce(trim(p_title), '')) < 3 then raise exception 'Escreva um título'; end if;
  insert into public.notifications (user_id, title, body, created_by)
  select id, trim(p_title), nullif(trim(p_body), ''), auth.uid() from public.profiles
  where (p_user is null and not blocked) or id = p_user;
  get diagnostics v_n = row_count;
  perform public._audit('usuario.mensagem', 'profile', coalesce(p_user::text, 'todos'), null, null,
                        jsonb_build_object('titulo', p_title, 'texto', p_body, 'destinatarios', v_n));
  return v_n;
end $$;

create or replace function public.mark_notifications_read() returns void
language sql security definer set search_path = public as $$
  update public.notifications set read_at = now() where user_id = auth.uid() and read_at is null
$$;

