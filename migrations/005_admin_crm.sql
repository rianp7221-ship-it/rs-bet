-- ---------- NÍVEL DE RISCO ----------
create or replace function public.admin_set_risk(p_user uuid, p_level text, p_reason text) returns void
language plpgsql security definer set search_path = public as $$
declare v_old text;
begin
  perform public._require_perm('users.block');
  if p_level not in ('baixo','medio','alto') then raise exception 'Nível inválido'; end if;
  select risk_level into v_old from public.profiles where id = p_user for update;
  if not found then raise exception 'Usuário não encontrado'; end if;
  update public.profiles set risk_level = p_level where id = p_user;
  perform public._audit('usuario.risco', 'profile', p_user::text, p_reason, jsonb_build_object('risk_level', v_old), jsonb_build_object('risk_level', p_level));
end $$;

