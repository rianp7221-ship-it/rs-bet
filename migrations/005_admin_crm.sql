create table if not exists public.pending_actions (
  id bigint generated by default as identity primary key,
  kind text not null, payload jsonb not null,
  requested_by uuid, requested_email text,
  status text not null default 'pendente' check (status in ('pendente','aprovado','recusado')),
  decided_by uuid, decided_email text, decision_reason text,
  created_at timestamptz not null default now(), decided_at timestamptz
);

drop function if exists public.admin_adjust_balance(uuid, numeric, text);
create or replace function public.admin_adjust_balance(p_user uuid, p_amount numeric, p_reason text) returns text
language plpgsql security definer set search_path = public as $$
declare v_before numeric; v_limit numeric := coalesce((public._setting('adjust_dual_limit'))::text::numeric, 0);
begin
  perform public._require_perm('users.balance');
  if length(coalesce(trim(p_reason), '')) < 5 then raise exception 'Informe o motivo do ajuste'; end if;
  if p_amount is null or p_amount = 0 then raise exception 'Valor inválido'; end if;
  select balance into v_before from public.profiles where id = p_user for update;
  if not found then raise exception 'Usuário não encontrado'; end if;
  if v_limit > 0 and abs(p_amount) >= v_limit then
    insert into public.pending_actions (kind, payload, requested_by, requested_email)
    values ('ajuste_saldo', jsonb_build_object('user_id', p_user, 'amount', round(p_amount, 2), 'reason', trim(p_reason)),
            auth.uid(), (select email from public.profiles where id = auth.uid()));
    perform public._audit('usuario.ajuste_solicitado', 'profile', p_user::text, p_reason, null, jsonb_build_object('amount', round(p_amount, 2)));
    return 'pendente';
  end if;
  perform public._move(p_user, round(p_amount, 2), 'adjust', 'Ajuste: ' || trim(p_reason));
  perform public._audit('usuario.ajuste_saldo', 'profile', p_user::text, p_reason,
                        jsonb_build_object('balance', v_before), jsonb_build_object('balance', v_before + round(p_amount, 2)));
  return 'feito';
end $$;

create or replace function public.admin_decide_action(p_id bigint, p_approve boolean, p_reason text default null) returns void
language plpgsql security definer set search_path = public as $$
declare a public.pending_actions; v_before numeric;
begin
  perform public._require_perm('users.balance');
  select * into a from public.pending_actions where id = p_id and status = 'pendente' for update;
  if not found then raise exception 'Pedido não está pendente'; end if;
  if a.requested_by = auth.uid() then raise exception 'Outra pessoa precisa aprovar o seu pedido'; end if;
  update public.pending_actions set status = case when p_approve then 'aprovado' else 'recusado' end,
         decided_by = auth.uid(), decided_email = (select email from public.profiles where id = auth.uid()),
         decision_reason = p_reason, decided_at = now()
   where id = p_id;
  if p_approve and a.kind = 'ajuste_saldo' then
    select balance into v_before from public.profiles where id = (a.payload->>'user_id')::uuid for update;
    perform public._move((a.payload->>'user_id')::uuid, (a.payload->>'amount')::numeric, 'adjust', 'Ajuste: ' || (a.payload->>'reason'));
    perform public._audit('usuario.ajuste_saldo', 'profile', a.payload->>'user_id', a.payload->>'reason',
                          jsonb_build_object('balance', v_before, 'pedido', p_id, 'solicitante', a.requested_email),
                          jsonb_build_object('balance', v_before + (a.payload->>'amount')::numeric));
  else
    perform public._audit('pedido.recusado', 'pending_action', p_id::text, p_reason, a.payload, null);
  end if;
end $$;

