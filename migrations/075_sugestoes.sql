-- Sugestões dos jogadores ("O que podemos melhorar?"): o jogador envia pelo site, a equipe lê em Admin → Sugestões.
create table if not exists public.feedback (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  body text not null check (length(body) between 3 and 2000),
  created_at timestamptz not null default now()
);
create index if not exists feedback_created_idx on public.feedback (created_at desc);
alter table public.feedback enable row level security;

create or replace function public.send_feedback(p_body text) returns void
language plpgsql security definer set search_path = public as $$
declare v_uid uuid := auth.uid(); v_body text := trim(coalesce(p_body, ''));
begin
  if v_uid is null then raise exception 'Entre na sua conta para enviar'; end if;
  if length(v_body) < 3 then raise exception 'Escreva sua sugestão'; end if;
  if length(v_body) > 2000 then raise exception 'Texto muito longo (máx. 2000 caracteres)'; end if;
  if (select count(*) from public.feedback f where f.user_id = v_uid and f.created_at > now() - interval '1 day') >= 5 then
    raise exception 'Você já enviou várias sugestões hoje. Obrigado!';
  end if;
  insert into public.feedback (user_id, body) values (v_uid, v_body);
end $$;

create or replace function public.admin_feedback(p_limit int default 500)
returns table (id bigint, created_at timestamptz, user_id uuid, email text, username text, body text)
language plpgsql security definer set search_path = public as $$
begin
  perform public._require_perm('users.view');
  return query select f.id, f.created_at, f.user_id, p.email, p.username, f.body
    from public.feedback f join public.profiles p on p.id = f.user_id
    order by f.created_at desc limit least(greatest(coalesce(p_limit, 500), 1), 2000);
end $$;

revoke all on function public.send_feedback(text) from public, anon;
revoke all on function public.admin_feedback(int) from public, anon;
grant execute on function public.send_feedback(text) to authenticated;
grant execute on function public.admin_feedback(int) to authenticated, service_role;
notify pgrst, 'reload schema';
