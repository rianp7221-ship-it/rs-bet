-- ---------- KYC ----------
create table if not exists public.kyc_documents (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  doc_type text not null check (doc_type in ('rg','cnh','comprovante','selfie')),
  path text not null,
  status text not null default 'em_analise' check (status in ('em_analise','aprovado','rejeitado')),
  reason text, reviewed_by uuid, reviewed_at timestamptz,
  created_at timestamptz not null default now()
);
create index if not exists kyc_status_idx on public.kyc_documents (status, created_at);

create or replace function public._kyc_refresh(p_user uuid) returns void
language sql security definer set search_path = public as $$
  update public.profiles set kyc_status = case
    when exists (select 1 from public.kyc_documents where user_id = p_user and status = 'aprovado' and doc_type in ('rg','cnh'))
     and exists (select 1 from public.kyc_documents where user_id = p_user and status = 'aprovado' and doc_type = 'comprovante') then 'aprovado'
    when exists (select 1 from public.kyc_documents where user_id = p_user and status = 'em_analise') then 'em_analise'
    when exists (select 1 from public.kyc_documents where user_id = p_user and status = 'rejeitado') then 'rejeitado'
    else 'pendente' end
  where id = p_user
$$;

create or replace function public.kyc_submit(p_doc_type text, p_path text) returns bigint
language plpgsql security definer set search_path = public as $$
declare v_user uuid := public._me(); v_id bigint;
begin
  if p_path is null or split_part(p_path, '/', 1) <> v_user::text then raise exception 'Arquivo inválido'; end if;
  if (select count(*) from public.kyc_documents where user_id = v_user and status = 'em_analise') >= 6 then
    raise exception 'Aguarde a análise dos documentos enviados'; end if;
  insert into public.kyc_documents (user_id, doc_type, path) values (v_user, p_doc_type, p_path) returning id into v_id;
  perform public._kyc_refresh(v_user);
  return v_id;
end $$;

create or replace function public.admin_kyc_review(p_id bigint, p_approve boolean, p_reason text) returns void
language plpgsql security definer set search_path = public as $$
declare d public.kyc_documents;
begin
  perform public._require_perm('kyc.manage');
  if not p_approve and length(coalesce(trim(p_reason), '')) < 5 then raise exception 'Informe o motivo da rejeição'; end if;
  select * into d from public.kyc_documents where id = p_id and status = 'em_analise' for update;
  if not found then raise exception 'Documento não está em análise'; end if;
  update public.kyc_documents set status = case when p_approve then 'aprovado' else 'rejeitado' end,
         reason = p_reason, reviewed_by = auth.uid(), reviewed_at = now() where id = p_id;
  perform public._kyc_refresh(d.user_id);
  insert into public.notifications (user_id, title, body, created_by) values (d.user_id,
    case when p_approve then 'Documento aprovado' else 'Documento rejeitado' end,
    case when p_approve then 'Seu documento foi aprovado.' else 'Motivo: ' || p_reason || '. Envie um novo arquivo em Minha conta → Verificação.' end, auth.uid());
  perform public._audit(case when p_approve then 'kyc.aprovar' else 'kyc.rejeitar' end, 'kyc_document', p_id::text, p_reason,
                        jsonb_build_object('user_id', d.user_id, 'doc_type', d.doc_type), null);
end $$;

-- saque passa por revisão manual enquanto o KYC não estiver aprovado
create or replace function public._classify_withdraw(p_user uuid, p_amount numeric) returns text[]
language plpgsql stable security definer set search_path = public as $$
declare v_p public.profiles; v_reasons text[] := '{}'; v_dep numeric; v_bet numeric;
  v_fast numeric := coalesce((public._setting('withdraw_fast_limit'))::text::numeric, 0);
  v_dual numeric := coalesce((public._setting('withdraw_dual_limit'))::text::numeric, 0);
begin
  select * into v_p from public.profiles where id = p_user;
  if coalesce((public._setting('kyc_required_withdraw'))::text, 'true') = 'true' and v_p.kyc_status <> 'aprovado' then
    v_reasons := v_reasons || ('KYC ' || replace(v_p.kyc_status, '_', ' ')); end if;
  if v_p.risk_level <> 'baixo' then v_reasons := v_reasons || ('risco ' || v_p.risk_level); end if;
  if exists (select 1 from public.alerts where user_id = p_user and status <> 'resolvido') then v_reasons := v_reasons || 'alerta aberto'::text; end if;
  if exists (select 1 from public.chargebacks where user_id = p_user and status in ('aberto','contestado')) then v_reasons := v_reasons || 'chargeback aberto'::text; end if;
  select coalesce(sum(amount), 0) into v_dep from public.transactions where user_id = p_user and type = 'deposit' and status = 'done';
  select coalesce(-sum(amount), 0) into v_bet from public.transactions where user_id = p_user and type in ('bet','casino_bet') and status = 'done';
  if v_bet < v_dep then v_reasons := v_reasons || format('apostou R$ %s de R$ %s depositados', v_bet, v_dep); end if;
  if p_amount > v_fast then v_reasons := v_reasons || format('acima de R$ %s', v_fast); end if;
  return array[case when v_dual > 0 and p_amount >= v_dual then 'dupla' when cardinality(v_reasons) = 0 then 'rapido' else 'manual' end]
         || v_reasons;
end $$;

-- ---------- CHARGEBACKS / CONTESTAÇÕES DE PIX ----------
create table if not exists public.chargebacks (
  id bigint generated by default as identity primary key,
  tx_id bigint not null unique references public.transactions(id),
  user_id uuid not null references public.profiles(id) on delete cascade,
  amount numeric(14,2) not null, recovered numeric(14,2) not null default 0,
  reason text not null, notes text,
  status text not null default 'aberto' check (status in ('aberto','contestado','perdido','ganho')),
  created_by uuid, created_at timestamptz not null default now(), updated_at timestamptz
);

-- abre contestação: debita do saldo o que houver (até o valor), sobe o risco e gera alerta
create or replace function public.admin_chargeback_open(p_tx bigint, p_reason text) returns bigint
language plpgsql security definer set search_path = public as $$
declare t public.transactions; v_bal numeric; v_take numeric; v_id bigint;
begin
  perform public._require_perm('chargeback.manage');
  if length(coalesce(trim(p_reason), '')) < 5 then raise exception 'Informe o motivo'; end if;
  select * into t from public.transactions where id = p_tx and type = 'deposit' and status = 'done';
  if not found then raise exception 'Só depósitos concluídos podem ser contestados'; end if;
  select balance into v_bal from public.profiles where id = t.user_id for update;
  v_take := least(v_bal, t.amount);
  if v_take > 0 then perform public._move(t.user_id, -v_take, 'chargeback', 'Contestação do depósito #' || p_tx); end if;
  insert into public.chargebacks (tx_id, user_id, amount, recovered, reason, created_by)
  values (p_tx, t.user_id, t.amount, v_take, trim(p_reason), auth.uid()) returning id into v_id;
  update public.profiles set risk_level = 'alto' where id = t.user_id;
  perform public._alert('chargeback', 'critica', t.user_id, 'cb:' || v_id, format('Contestação de R$ %s no depósito #%s (recuperado R$ %s)', t.amount, p_tx, v_take));
  perform public._audit('chargeback.abrir', 'transaction', p_tx::text, p_reason, jsonb_build_object('balance', v_bal), jsonb_build_object('recuperado', v_take));
  return v_id;
end $$;

create or replace function public.admin_chargeback_update(p_id bigint, p_status text, p_notes text) returns void
language plpgsql security definer set search_path = public as $$
declare c public.chargebacks;
begin
  perform public._require_perm('chargeback.manage');
  if p_status not in ('aberto','contestado','perdido','ganho') then raise exception 'Status inválido'; end if;
  select * into c from public.chargebacks where id = p_id for update;
  if not found then raise exception 'Não encontrado'; end if;
  if p_status = 'ganho' and c.status <> 'ganho' and c.recovered > 0 then
    perform public._move(c.user_id, c.recovered, 'refund', 'Contestação #' || p_id || ' encerrada a favor do jogador');
  end if;
  update public.chargebacks set status = p_status, notes = coalesce(nullif(trim(p_notes), ''), notes), updated_at = now() where id = p_id;
  perform public._audit('chargeback.status', 'chargeback', p_id::text, p_notes, jsonb_build_object('status', c.status), jsonb_build_object('status', p_status));
end $$;

-- ---------- APOSTAS SUSPEITAS ----------
create or replace function public.admin_suspicious_bets(p_days int default 7) returns jsonb
language plpgsql stable security definer set search_path = public as $$
begin
  perform public._require_perm('alerts.view');
  return coalesce((select jsonb_agg(to_jsonb(x) order by x.created_at desc) from (
    select b.id, b.user_id, p.email, p.risk_level, b.stake, b.total_odd, b.potential, b.status, b.created_at,
      array_remove(array[
        case when b.total_odd >= 30 and b.stake >= 100 then 'múltipla de alto risco' end,
        case when avg_s.n >= 5 and b.stake >= 5 * avg_s.a then format('aposta %sx acima da média', round(b.stake / nullif(avg_s.a, 0))) end,
        case when exists (select 1 from public.bet_selections s1 join public.bets b2 on b2.user_id = b.user_id and b2.id <> b.id
                          join public.bet_selections s2 on s2.bet_id = b2.id and s2.match_id = s1.match_id and s2.pick <> s1.pick
                          where s1.bet_id = b.id) then 'apostou nos dois lados do jogo (surebet)' end,
        case when exists (select 1 from public.bet_selections s1
                          join public.bet_selections s2 on s2.match_id = s1.match_id and s2.pick = s1.pick and s2.bet_id <> s1.bet_id
                          join public.bets b2 on b2.id = s2.bet_id and b2.user_id <> b.user_id
                          join public.device_logs d1 on d1.user_id = b.user_id
                          join public.device_logs d2 on d2.user_id = b2.user_id and (d2.fingerprint = d1.fingerprint or d2.ip = d1.ip)
                          where s1.bet_id = b.id) then 'contas ligadas no mesmo palpite' end
      ], null) as reasons
    from public.bets b join public.profiles p on p.id = b.user_id
    left join lateral (select count(*) n, avg(stake) a from public.bets o where o.user_id = b.user_id and o.id <> b.id) avg_s on true
    where b.created_at > now() - make_interval(days => p_days)) x where cardinality(x.reasons) > 0), '[]');
end $$;

-- ---------- RLS / STORAGE ----------
alter table public.kyc_documents enable row level security;
alter table public.chargebacks enable row level security;
revoke all on public.kyc_documents, public.chargebacks from anon, authenticated;
grant select on public.kyc_documents, public.chargebacks to authenticated;
drop policy if exists "kyc_read" on public.kyc_documents;
create policy "kyc_read" on public.kyc_documents for select to authenticated using (user_id = auth.uid() or public.has_perm('kyc.view'));
drop policy if exists "chargebacks_read" on public.chargebacks;
create policy "chargebacks_read" on public.chargebacks for select to authenticated using (public.has_perm('chargeback.manage') or public.has_perm('finance.view'));
revoke execute on function public._kyc_refresh(uuid) from public, anon, authenticated;
grant execute on function public.kyc_submit(text, text), public.admin_kyc_review(bigint, boolean, text),
  public.admin_chargeback_open(bigint, text), public.admin_chargeback_update(bigint, text, text), public.admin_suspicious_bets(int) to authenticated;

