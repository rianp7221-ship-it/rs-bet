-- Notificação no celular (Web Push) das mensagens/promoções enviadas pelo admin, e "Limpar" notificações.
-- A Edge Function push-send (--no-verify-jwt, header x-cron-secret) envia a fila push_outbox
-- usando as chaves VAPID_PUBLIC_KEY / VAPID_PRIVATE_KEY / VAPID_SUBJECT.

create table if not exists public.push_subscriptions (
  endpoint text primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  p256dh text not null,
  auth text not null,
  created_at timestamptz not null default now()
);
create index if not exists push_subscriptions_user_idx on public.push_subscriptions (user_id);
alter table public.push_subscriptions enable row level security;
revoke all on public.push_subscriptions from anon, authenticated;

create table if not exists public.push_outbox (
  id bigint generated by default as identity primary key,
  user_id uuid,                -- null = todos os jogadores
  title text not null,
  body text,
  created_at timestamptz not null default now(),
  claimed_at timestamptz,
  done_at timestamptz,
  sent int,
  failed int
);
alter table public.push_outbox enable row level security;
revoke all on public.push_outbox from anon, authenticated;

create or replace function public.push_subscribe(p_endpoint text, p_p256dh text, p_auth text) returns void
language plpgsql security definer set search_path = public as $$
declare u uuid := auth.uid();
begin
  if u is null then raise exception 'Entre na sua conta'; end if;
  -- só serviços de push dos navegadores (Chrome/Android, Firefox, Safari/iOS, Edge)
  if p_endpoint !~ '^https://(fcm\.googleapis\.com|[a-z0-9-]+\.google\.com|updates\.push\.services\.mozilla\.com|[a-z0-9.-]+\.push\.apple\.com|[a-z0-9.-]+\.notify\.windows\.com)/'
     or length(p_endpoint) > 1000 or length(coalesce(p_p256dh, '')) not between 20 and 200
     or length(coalesce(p_auth, '')) not between 8 and 100 then
    raise exception 'Inscrição inválida';
  end if;
  insert into public.push_subscriptions (endpoint, user_id, p256dh, auth) values (p_endpoint, u, p_p256dh, p_auth)
  on conflict (endpoint) do update set user_id = excluded.user_id, p256dh = excluded.p256dh, auth = excluded.auth, created_at = now();
  -- no máximo 10 aparelhos por jogador
  delete from public.push_subscriptions where endpoint in (
    select endpoint from public.push_subscriptions where user_id = u order by created_at desc offset 10);
end $$;

create or replace function public.push_unsubscribe(p_endpoint text) returns void
language sql security definer set search_path = public as $$
  delete from public.push_subscriptions where endpoint = p_endpoint and user_id = auth.uid()
$$;

-- "Sair em todos os aparelhos": nenhum aparelho continua recebendo
create or replace function public.push_unsubscribe_all() returns void
language sql security definer set search_path = public as $$
  delete from public.push_subscriptions where user_id = auth.uid()
$$;

create or replace function public.clear_notifications() returns void
language sql security definer set search_path = public as $$
  delete from public.notifications where user_id = auth.uid()
$$;

revoke all on function public.push_subscribe(text, text, text), public.push_unsubscribe(text), public.push_unsubscribe_all(), public.clear_notifications() from public, anon;
grant execute on function public.push_subscribe(text, text, text), public.push_unsubscribe(text), public.push_unsubscribe_all(), public.clear_notifications() to authenticated;

-- usados só pela Edge Function (service_role)
create or replace function public.push_claim(p_limit int default 5) returns setof public.push_outbox
language sql security definer set search_path = public as $$
  update public.push_outbox set claimed_at = now()
  where id in (select id from public.push_outbox
               where done_at is null and (claimed_at is null or claimed_at < now() - interval '5 minutes')
               order by id limit p_limit for update skip locked)
  returning *
$$;

create or replace function public.push_targets(p_user uuid) returns table (endpoint text, p256dh text, auth text)
language sql stable security definer set search_path = public as $$
  select s.endpoint, s.p256dh, s.auth from public.push_subscriptions s join public.profiles p on p.id = s.user_id
  where (p_user is null and not p.blocked) or s.user_id = p_user
$$;

create or replace function public._call_push_send() returns bigint
language sql security definer set search_path = public as $$
  select net.http_post(
    url := 'https://pscpcxleyysspvwkevpe.supabase.co/functions/v1/push-send',
    headers := jsonb_build_object('Content-Type', 'application/json',
      'x-cron-secret', (select decrypted_secret from vault.decrypted_secrets where name = 'sync_odds_cron_secret')),
    body := '{}'::jsonb,
    timeout_milliseconds := 60000)
$$;

revoke all on function public.push_claim(int), public.push_targets(uuid), public._call_push_send() from public, anon, authenticated;

create or replace function public.admin_send_notification(p_user uuid, p_title text, p_body text) returns int
language plpgsql security definer set search_path = public as $$
declare v_n int;
begin
  perform public._require_perm('users.message');
  if length(coalesce(trim(p_title), '')) < 3 then raise exception 'Escreva um título'; end if;
  insert into public.notifications (user_id, title, body, created_by)
  select id, trim(p_title), nullif(trim(p_body), ''), auth.uid() from public.profiles
  where (p_user is null and not blocked) or id = p_user;
  get diagnostics v_n = row_count;
  if v_n > 0 then
    insert into public.push_outbox (user_id, title, body) values (p_user, trim(p_title), nullif(trim(p_body), ''));
    perform public._call_push_send();
  end if;
  perform public._audit('usuario.mensagem', 'profile', coalesce(p_user::text, 'todos'), null, null,
                        jsonb_build_object('titulo', p_title, 'texto', p_body, 'destinatarios', v_n));
  return v_n;
end $$;
