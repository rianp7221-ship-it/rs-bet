-- cashback: % das perdas líquidas do período, uma vez por jogador por período
create or replace function public.admin_run_cashback(p_campaign bigint, p_from timestamptz, p_to timestamptz) returns jsonb
language plpgsql security definer set search_path = public as $$
declare c public.bonus_campaigns; r record; n int := 0; v_total numeric := 0; v_amt numeric;
begin
  perform public._require_perm('bonus.manage');
  select * into c from public.bonus_campaigns where id = p_campaign and kind = 'cashback' and active;
  if not found then raise exception 'Campanha de cashback inválida ou inativa'; end if;
  if p_to > now() or p_from >= p_to then raise exception 'Período inválido (precisa ter terminado)'; end if;
  for r in select user_id, -sum(amount) as loss from public.transactions
            where status = 'done' and type in ('bet','casino_bet','win','cashout','casino_win','bet_refund')
              and created_at >= p_from and created_at < p_to group by user_id having -sum(amount) > 0 loop
    v_amt := least(coalesce(c.max_amount, 1e12), round(r.loss * c.percent / 100, 2));
    if public._grant_bonus(r.user_id, c.id, 'cashback', v_amt, c.rollover, c.min_odd, c.valid_days, c.name,
                           format('cashback:%s:%s:%s', c.id, r.user_id, p_from::date)) is not null then
      n := n + 1; v_total := v_total + v_amt;
    end if;
  end loop;
  update public.bonus_campaigns set uses = uses + n where id = c.id;
  perform public._audit('bonus.cashback', 'bonus_campaign', c.id::text, format('%s a %s', p_from, p_to), null, jsonb_build_object('jogadores', n, 'total', v_total));
  return jsonb_build_object('players', n, 'total', v_total);
end $$;

