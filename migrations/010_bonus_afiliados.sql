  wager_required numeric(14,2) not null default 0, wagered numeric(14,2) not null default 0,
  min_odd numeric(6,2) not null default 1,
  status text not null default 'ativo' check (status in ('aguardando_deposito','ativo','concluido','expirado','cancelado')),
