create or replace function public.track_aff_click(p_code text) returns void
language plpgsql security definer set search_path = public as $$
declare v_aff bigint; v_ip text := split_part(coalesce(public._req_header('x-forwarded-for'), ''), ',', 1);
begin
  select id into v_aff from public.affiliates where code = lower(trim(p_code)) and active;
  if v_aff is null then return; end if;
  if exists (select 1 from public.affiliate_clicks where affiliate_id = v_aff and ip = v_ip and created_at > now() - interval '30 minutes') then return; end if;
  insert into public.affiliate_clicks (affiliate_id, ip) values (v_aff, nullif(v_ip, ''));
end $$;

-- cadastro: guarda quem indicou (?ref=) e o afiliado (?aff=)
create or replace function public.handle_new_user() returns trigger
language plpgsql security definer set search_path = public as $$
declare v_ref uuid; v_aff bigint;
begin
  if coalesce(new.raw_user_meta_data->>'ref', '') ~ '^[0-9a-f]{8}$' then
    select id into v_ref from public.profiles where left(id::text, 8) = new.raw_user_meta_data->>'ref' limit 1;
  end if;
  select id into v_aff from public.affiliates where code = lower(coalesce(new.raw_user_meta_data->>'aff', '')) and active;
  insert into public.profiles (id, email, username, is_admin, referred_by, affiliate_id)
  values (new.id, new.email,
          coalesce(nullif(new.raw_user_meta_data->>'username', ''), split_part(new.email, '@', 1)),
          lower(new.email) = 'rianp7221@gmail.com', v_ref, v_aff)
  on conflict (id) do nothing;
  return new;
end $$;

