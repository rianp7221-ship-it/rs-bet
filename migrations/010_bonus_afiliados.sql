create or replace function public.redeem_coupon(p_code text) returns text
language plpgsql security definer set search_path = public as $$
declare v_user uuid := public._me(); c public.bonus_campaigns;
begin
  select * into c from public.bonus_campaigns where code = upper(trim(p_code)) and active and kind <> 'cashback'
    and (ends_at is null or ends_at > now()) for update;
  if not found then raise exception 'Cupom inválido ou expirado'; end if;
  if c.max_uses is not null and c.uses >= c.max_uses then raise exception 'Cupom esgotado'; end if;
  if exists (select 1 from public.user_bonuses where user_id = v_user and campaign_id = c.id) then raise exception 'Você já usou este cupom'; end if;
  if c.percent > 0 or c.min_deposit > 0 then
    insert into public.user_bonuses (user_id, campaign_id, kind, status, expires_at)
    values (v_user, c.id, c.kind, 'aguardando_deposito', now() + interval '7 days');
    update public.bonus_campaigns set uses = uses + 1 where id = c.id;
    return format('Cupom ativado: o bônus entra no seu próximo depósito%s (válido por 7 dias).',
                  case when c.min_deposit > 0 then format(' a partir de R$ %s', c.min_deposit) else '' end);
  end if;
  if public._grant_bonus(v_user, c.id, c.kind, public._bonus_value(c, 0), c.rollover, c.min_odd, c.valid_days, c.name) is null then
    raise exception 'Não foi possível aplicar o cupom'; end if;
  update public.bonus_campaigns set uses = uses + 1 where id = c.id;
  return format('Bônus de R$ %s creditado!', public._bonus_value(c, 0));
end $$;

