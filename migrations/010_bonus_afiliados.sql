create or replace function public.admin_save_campaign(p jsonb) returns bigint
language plpgsql security definer set search_path = public as $$
declare v_id bigint := nullif(p->>'id', '')::bigint; v_before jsonb;
begin
  perform public._require_perm('bonus.manage');
  if v_id is null then
    insert into public.bonus_campaigns (name, kind, code, percent, fixed, max_amount, min_deposit, rollover, min_odd, valid_days, max_uses, ends_at, active, created_by)
    values (p->>'name', p->>'kind', nullif(upper(trim(p->>'code')), ''), coalesce((p->>'percent')::numeric, 0), coalesce((p->>'fixed')::numeric, 0),
            nullif(p->>'max_amount', '')::numeric, coalesce(nullif(p->>'min_deposit', '')::numeric, 0), coalesce(nullif(p->>'rollover', '')::numeric, 1),
            coalesce(nullif(p->>'min_odd', '')::numeric, 1.5), coalesce(nullif(p->>'valid_days', '')::int, 30), nullif(p->>'max_uses', '')::int,
            nullif(p->>'ends_at', '')::timestamptz, coalesce((p->>'active')::boolean, true), auth.uid())
    returning id into v_id;
  else
    select to_jsonb(c) into v_before from public.bonus_campaigns c where id = v_id;
    update public.bonus_campaigns set active = coalesce((p->>'active')::boolean, active),
      ends_at = case when p ? 'ends_at' then nullif(p->>'ends_at', '')::timestamptz else ends_at end,
      max_uses = case when p ? 'max_uses' then nullif(p->>'max_uses', '')::int else max_uses end where id = v_id;
  end if;
  perform public._audit('bonus.campanha', 'bonus_campaign', v_id::text, null, v_before, (select to_jsonb(c) from public.bonus_campaigns c where id = v_id));
  return v_id;
end $$;

