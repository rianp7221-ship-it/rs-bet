create unique index if not exists user_bonuses_source on public.user_bonuses (source) where source is not null;

-- ---------- NÚCLEO ----------
create or replace function public._grant_bonus(p_user uuid, p_campaign bigint, p_kind text, p_amount numeric, p_rollover numeric,
                                               p_min_odd numeric, p_days int, p_label text, p_source text default null) returns bigint
language plpgsql security definer set search_path = public as $$
declare v_id bigint; l public.user_limits;
begin
  p_amount := round(coalesce(p_amount, 0), 2);
  if p_amount <= 0 then return null; end if;
  l := public._limits(p_user);
  if l.self_excluded_until > now() then return null; end if;
  insert into public.user_bonuses (user_id, campaign_id, kind, source, amount, wager_required, min_odd, expires_at)
  values (p_user, p_campaign, p_kind, p_source, p_amount, round(p_amount * coalesce(p_rollover, 0), 2), coalesce(p_min_odd, 1),
          now() + make_interval(days => coalesce(p_days, 30)))
  on conflict do nothing returning id into v_id;
  if v_id is null then return null; end if;
  perform public._move(p_user, p_amount, 'bonus', 'Bônus: ' || p_label);
  insert into public.notifications (user_id, title, body) values (p_user, 'Bônus creditado',
    format('Você recebeu R$ %s (%s). %s', p_amount, p_label,
      case when p_rollover > 0 then format('Aposte R$ %s em %s dias para liberar o saque.', round(p_amount * p_rollover, 2), coalesce(p_days, 30)) else 'Já pode usar e sacar.' end));
  return v_id;
end $$;

create or replace function public._bonus_value(c public.bonus_campaigns, p_dep numeric) returns numeric
language sql immutable as $$
  select least(coalesce(c.max_amount, 1e12), c.fixed + round(coalesce(p_dep, 0) * c.percent / 100, 2))
$$;

-- avança o rollover: apostas esportivas contam se a odd >= mínima do bônus; cassino conta sempre
create or replace function public._bonus_wager(p_user uuid, p_amount numeric, p_odd numeric) returns void
language sql security definer set search_path = public as $$
  update public.user_bonuses set wagered = least(wager_required, wagered + p_amount),
    status = case when wagered + p_amount >= wager_required then 'concluido' else status end,
    finished_at = case when wagered + p_amount >= wager_required then now() end
  where user_id = p_user and status = 'ativo' and expires_at > now() and (p_odd is null or p_odd >= min_odd)
$$;

create or replace function public._bonus_on_bet() returns trigger
language plpgsql security definer set search_path = public as $$
begin perform public._bonus_wager(new.user_id, new.stake, new.total_odd); return new; end $$;
drop trigger if exists bonus_on_bet on public.bets;
create trigger bonus_on_bet after insert on public.bets for each row execute function public._bonus_on_bet();

-- remove o bônus não cumprido (até o saldo disponível)
create or replace function public._bonus_forfeit(b public.user_bonuses, p_status text) returns void
language plpgsql security definer set search_path = public as $$
declare v_take numeric;
begin
  update public.user_bonuses set status = p_status, finished_at = now() where id = b.id;
  if b.status <> 'ativo' then return; end if;
  select least(balance, b.amount) into v_take from public.profiles where id = b.user_id for update;
  if v_take > 0 then perform public._move(b.user_id, -v_take, 'bonus_expire', 'Bônus ' || p_status || ' #' || b.id); end if;
end $$;

create or replace function public._expire_bonuses(p_user uuid default null) returns int
language plpgsql security definer set search_path = public as $$
declare b public.user_bonuses; n int := 0;
begin
  for b in select * from public.user_bonuses where status in ('ativo','aguardando_deposito') and expires_at <= now()
             and (p_user is null or user_id = p_user) for update skip locked loop
    perform public._bonus_forfeit(b, 'expirado'); n := n + 1;
  end loop;
  return n;
end $$;

-- transações: rollover do cassino e eventos do depósito aprovado (cupom, boas-vindas, indicação)
create or replace function public._bonus_on_tx() returns trigger
language plpgsql security definer set search_path = public as $$
declare b public.user_bonuses; c public.bonus_campaigns; p public.profiles; v_amt numeric; v_used boolean := false;
begin
  if tg_op = 'INSERT' and new.type = 'casino_bet' and new.status = 'done' then
    perform public._bonus_wager(new.user_id, -new.amount, null); return new;
  end if;
  if new.type <> 'deposit' or new.status <> 'done' or (tg_op = 'UPDATE' and old.status = 'done') then return new; end if;
  -- cupom aguardando depósito
  for b in select * from public.user_bonuses where user_id = new.user_id and status = 'aguardando_deposito' and expires_at > now()
             order by created_at limit 1 for update loop
    select * into c from public.bonus_campaigns where id = b.campaign_id;
    if c.id is not null and new.amount >= c.min_deposit then
      v_amt := public._bonus_value(c, new.amount);
      update public.user_bonuses set status = 'ativo', amount = v_amt, wager_required = round(v_amt * c.rollover, 2),
             min_odd = c.min_odd, expires_at = now() + make_interval(days => c.valid_days) where id = b.id;
      perform public._move(new.user_id, v_amt, 'bonus', 'Bônus: ' || c.name);
      insert into public.notifications (user_id, title, body) values (new.user_id, 'Bônus creditado',
        format('Você recebeu R$ %s (%s). Aposte R$ %s em %s dias para liberar o saque.', v_amt, c.name, round(v_amt * c.rollover, 2), c.valid_days));
      v_used := true;
    end if;
  end loop;
  if exists (select 1 from public.transactions where user_id = new.user_id and type = 'deposit' and status = 'done' and id <> new.id) then return new; end if;
  -- 1º depósito: boas-vindas automático
  if not v_used then
    select * into c from public.bonus_campaigns where kind = 'boas_vindas' and active and code is null and min_deposit <= new.amount
      and (ends_at is null or ends_at > now()) and (max_uses is null or uses < max_uses) order by created_at desc limit 1;
    if c.id is not null and public._grant_bonus(new.user_id, c.id, c.kind, public._bonus_value(c, new.amount), c.rollover, c.min_odd, c.valid_days, c.name) is not null then
      update public.bonus_campaigns set uses = uses + 1 where id = c.id;
    end if;
  end if;
  -- indicação: quem indicou ganha quando o indicado faz o 1º depósito mínimo
  select * into p from public.profiles where id = new.user_id;
  if p.referred_by is not null and new.amount >= coalesce((public._setting('referral_min_deposit'))::text::numeric, 0) then
    perform public._grant_bonus(p.referred_by, null, 'indicacao', coalesce((public._setting('referral_reward'))::text::numeric, 0),
      coalesce((public._setting('referral_rollover'))::text::numeric, 1), 1.5, 30, 'indicação de ' || coalesce(p.username, 'amigo'), 'indicacao:' || new.user_id);
  end if;
  return new;
end $$;
drop trigger if exists bonus_on_tx on public.transactions;
create trigger bonus_on_tx after insert or update of status on public.transactions for each row execute function public._bonus_on_tx();

-- saque só depois de cumprir o rollover
create or replace function public.request_withdraw(p_amount numeric) returns bigint
language plpgsql security definer set search_path = public as $$
declare v_user uuid := public._me(); v_id bigint; v_c text[]; v_today numeric; v_left numeric;
  v_max numeric := coalesce((public._setting('withdraw_daily_max'))::text::numeric, 0);
begin
  if p_amount is null or p_amount < 20 then raise exception 'Saque mínimo: R$ 20,00'; end if;
  perform public._expire_bonuses(v_user);
  select sum(wager_required - wagered) into v_left from public.user_bonuses where user_id = v_user and status = 'ativo';
  if v_left > 0 then raise exception 'Cumpra o rollover do bônus antes de sacar: faltam R$ % em apostas (ou cancele o bônus em Minha conta → Bônus)', round(v_left, 2); end if;
  select coalesce(-sum(amount), 0) into v_today from public.transactions
   where user_id = v_user and type = 'withdraw' and status in ('pending','done') and created_at > now() - interval '1 day';
  if v_max > 0 and v_today + p_amount > v_max then raise exception 'Limite diário de saque: R$ %', v_max; end if;
  v_c := public._classify_withdraw(v_user, round(p_amount, 2));
  update public.profiles set balance = balance - round(p_amount, 2) where id = v_user and balance >= round(p_amount, 2);
  if not found then raise exception 'Saldo insuficiente'; end if;
  insert into public.transactions (user_id, type, amount, status, description, review_level, review_notes)
  values (v_user, 'withdraw', -round(p_amount, 2), 'pending', 'Saque PIX', v_c[1], nullif(array_to_string(v_c[2:], ' · '), ''))
  returning id into v_id;
  return v_id;
end $$;

