create or replace function public.admin_affiliate_report(p_from timestamptz, p_to timestamptz) returns jsonb
language plpgsql stable security definer set search_path = public as $$
begin
  perform public._require_perm('affiliates.manage');
  return coalesce((select jsonb_agg(to_jsonb(x) || jsonb_build_object('commission',
      round(case when x.model in ('cpa','hibrido') then x.cpa_value * x.ftd_ok else 0 end
          + case when x.model in ('revshare','hibrido') then greatest(x.ngr, 0) * x.revshare_pct / 100 else 0 end, 2)) order by x.name) from (
    select a.id, a.name, a.code, a.model, a.cpa_value, a.revshare_pct, a.active,
      (select count(*) from public.affiliate_clicks k where k.affiliate_id = a.id and k.created_at >= p_from and k.created_at < p_to) as clicks,
      (select count(*) from public.profiles p where p.affiliate_id = a.id and p.created_at >= p_from and p.created_at < p_to) as signups,
      (select count(*) from (select t.user_id, min(coalesce(t.reviewed_at, t.created_at)) f,
                                    (array_agg(t.amount order by coalesce(t.reviewed_at, t.created_at)))[1] amt
                             from public.transactions t join public.profiles p on p.id = t.user_id and p.affiliate_id = a.id
                             where t.type = 'deposit' and t.status = 'done' group by t.user_id) d where d.f >= p_from and d.f < p_to) as ftd,
      (select count(*) from (select t.user_id, min(coalesce(t.reviewed_at, t.created_at)) f,
                                    (array_agg(t.amount order by coalesce(t.reviewed_at, t.created_at)))[1] amt
                             from public.transactions t join public.profiles p on p.id = t.user_id and p.affiliate_id = a.id
                             where t.type = 'deposit' and t.status = 'done' group by t.user_id) d
        where d.f >= p_from and d.f < p_to and d.amt >= a.cpa_min_deposit) as ftd_ok,
      (select coalesce(sum(t.amount) filter (where t.type = 'deposit'), 0) from public.transactions t join public.profiles p on p.id = t.user_id and p.affiliate_id = a.id
        where t.status = 'done' and coalesce(t.reviewed_at, t.created_at) >= p_from and coalesce(t.reviewed_at, t.created_at) < p_to) as deposits,
      (select coalesce(-sum(t.amount) filter (where t.type in ('bet','casino_bet','win','cashout','casino_win','bet_refund','bonus')), 0)
        from public.transactions t join public.profiles p on p.id = t.user_id and p.affiliate_id = a.id
        where t.status = 'done' and t.created_at >= p_from and t.created_at < p_to) as ngr
    from public.affiliates a) x), '[]');
end $$;

create or replace function public.admin_referrals() returns jsonb
language plpgsql stable security definer set search_path = public as $$
begin
  perform public._require_perm('bonus.view');
  return coalesce((select jsonb_agg(to_jsonb(x) order by x.invited desc) from (
    select r.id, r.email, count(p.id) as invited,
      (select count(*) from public.user_bonuses b where b.user_id = r.id and b.kind = 'indicacao') as qualified,
      (select coalesce(sum(amount), 0) from public.user_bonuses b where b.user_id = r.id and b.kind = 'indicacao') as earned
    from public.profiles r join public.profiles p on p.referred_by = r.id group by r.id) x), '[]');
end $$;

