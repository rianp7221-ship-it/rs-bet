  fixed numeric(14,2) not null default 0 check (fixed >= 0),
  max_amount numeric(14,2), min_deposit numeric(14,2) not null default 0,
  rollover numeric(6,2) not null default 1 check (rollover >= 0),
  min_odd numeric(6,2) not null default 1.5,
